  var ATTRS = ['alt', 'aria-label', 'placeholder', 'title'];
  var origText = new WeakMap();

  function translateNode(node) {
    var cur = node.nodeValue;
    var key = norm(cur);
    if (!key) return;
    var rec = origText.get(node);
    if (rec && rec.shown !== cur) { origText.delete(node); rec = null; } // changed by a script
    if (lang === 'sk') {
      if (rec) { node.nodeValue = rec.orig; origText.delete(node); }
      else if (REV[key] && REV[key] !== key) node.nodeValue = cur.match(/^\s*/)[0] + REV[key] + cur.match(/\s*$/)[0];
      return;
    }
    var sk = rec ? norm(rec.orig) : key;
    if (!EN[sk]) return;
    var orig = rec ? rec.orig : cur;
    var out = orig.match(/^\s*/)[0] + EN[sk] + orig.match(/\s*$/)[0];
    node.nodeValue = out;
    origText.set(node, { orig: orig, shown: out });
  }

  function translateAttrs(el) {
    ATTRS.forEach(function (a) {
      if (!el.hasAttribute(a)) return;
      var store = 'data-sk-' + a;
      var sk = el.getAttribute(store);
      if (sk === null) {
        sk = el.getAttribute(a);
        if (!EN[norm(sk)]) return;
        el.setAttribute(store, sk);
      }
      el.setAttribute(a, lang === 'en' ? (EN[norm(sk)] || sk) : sk);
    });
  }

  function apply(root) {
    root = root || document.body;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode && n.parentNode.nodeName;
        return (p === 'SCRIPT' || p === 'STYLE') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = walker.nextNode())) translateNode(n);
    if (root.querySelectorAll) {
      Array.prototype.forEach.call(root.querySelectorAll('[alt],[aria-label],[placeholder],[title]'), translateAttrs);
    }
  }

